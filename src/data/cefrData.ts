export const getCEFRTranslation = (lang?: string): TranslationDictionary => {
  if (!lang) return TRANSLATIONS.fa;
  if (lang === 'fa' || lang === 'prs' || lang === 'ar' || lang === 'ps') {
    return TRANSLATIONS.fa;
  }
  if (lang === 'de') {
    return TRANSLATIONS.de;
  }
  return TRANSLATIONS.en || TRANSLATIONS.fa;
};
